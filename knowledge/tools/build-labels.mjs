/** 一对取值的规范键：与顺序无关。 */
function pairKey(left, right) {
  return [left, right].sort().join('\u0000');
}

export function buildLabels() {
  const fields = [];
  const positiveSeen = new Set();
  const negativeSeen = new Set();
  const positivePairs = [];
  const negativePairs = [];

  for (const [name, categories] of FIELDS) {
    fields.push({ name, values: categories.flatMap(([, variants]) => variants) });

    for (const [, variants] of categories) {
      for (let i = 0; i < variants.length; i += 1) {
        for (let j = i + 1; j < variants.length; j += 1) {
          const key = pairKey(variants[i], variants[j]);
          if (positiveSeen.has(key)) continue;
          positiveSeen.add(key);
          positivePairs.push([variants[i], variants[j]]);
        }
      }
    }

    for (let i = 0; i < categories.length; i += 1) {
      for (let j = i + 1; j < categories.length; j += 1) {
        for (const left of categories[i][1]) {
          for (const right of categories[j][1]) {
            // 去重是必须的，原因很具体：`小学／初中` 这类取值同时出现在
            // 「教育阶段」与「教育程度细分」两个字段里，会各生成一次。
            // 模型看到的只是两个字符串，重复的对不携带额外信息，只会让
            // Precision 的权重被同一个对悄悄乘两倍。
            const key = pairKey(left, right);
            if (negativeSeen.has(key)) continue;
            negativeSeen.add(key);
            negativePairs.push([left, right]);
          }
        }
      }
    }
  }

  return {
    说明:
      '类别同义归并的标注集。正例 = 同一个类别的两种写法；负例 = 同一字段内不同类别。' +
      '两者都只在同一字段内 —— 真实扫描是在一列内部两两比较的，跨字段的取值对不会出现，' +
      '混进来只会用大量平凡负例把 Precision 抬高。' +
      '本文件由 knowledge/tools/build-labels.mjs 生成，请勿手改；要加条目改那个脚本的分组。',
    fields,
    positivePairs,
    negativePairs,
  };
}

export function renderLabels() {
  return `${JSON.stringify(buildLabels(), null, 2)}\n`;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  const next = renderLabels();
  const checkOnly = process.argv.includes('--check');
  if (checkOnly) {
    let current = '';
    try {
      current = readFileSync(OUTPUT, 'utf8');
    } catch {
      console.error(`${OUTPUT} 不存在，先跑一次不带 --check 的`);
      process.exit(1);
    }
    if (current !== next) {
      console.error('标注集与生成器不一致：有人手改过 JSON，或者改了分组没重新生成。');
      console.error('跑 `node knowledge/tools/build-labels.mjs` 重新生成。');
      process.exit(1);
    }
    console.log('标注集与生成器一致');
    process.exit(0);
  }
  writeFileSync(OUTPUT, next, 'utf8');
  const labels = buildLabels();
  console.log(
    `${labels.fields.length} 字段 / 正例 ${labels.positivePairs.length} 对 / ` +
      `负例 ${labels.negativePairs.length} 对 → ${OUTPUT}`,
  );
}
